import assert from 'node:assert/strict';
import { backgroundHarness } from './background-harness.js';

let offline = false;
let reportStatus = 201;
let community = [];
const calls = [];
const anonymousToken = 'tcr_' + 'A'.repeat(43);
const client = backgroundHarness(async (url, options) => {
  calls.push({ url, ...options });
  if (offline) throw new Error('Network offline');
  if (url.endsWith('/api/register')) return new Response(JSON.stringify({success:true,token:anonymousToken,expires_at:Math.floor(Date.now()/1000)+365*86400}), {status:options.headers.Authorization ? 200 : 201});
  if (url.endsWith('/api/reports')) return new Response(JSON.stringify({success:reportStatus < 400,error:'Invalid reporter'}), {status:reportStatus});
  return new Response(JSON.stringify({success:true,data:community,revision:1,next_cursor:null}));
}, {tc_blocked_channels:{'@legacy':{channel_handle:'@legacy'}}});
const report = {channel_handle:'@spam',channel_name:'Spam',reason:'Repeated spam'};
assert.equal(Object.keys((await client.send({action:'GET_BLOCKED_CHANNELS'})).channels).length, 0, 'Unmoderated legacy cache must not become approved');
let result = await client.send({action:'SUBMIT_REPORT',data:report});
assert.equal(result.success, true);
assert.equal(result.queued, false);
assert.equal(calls.filter(c=>c.url.endsWith('/api/register')).length,1,'First report registers an anonymous identity');
assert.equal(calls.filter(c=>c.url.endsWith('/api/reports')).length,1,'First report is sent without manual setup');
assert.ok(client.broadcasts.at(-1).channels['@spam']);
await client.send({action:'FORCE_SYNC'});
assert.ok((await client.send({action:'GET_BLOCKED_CHANNELS'})).channels['@spam'], 'Sync preserves personal block');
offline = true;
await client.send({action:'SET_SETTINGS',url:'http://localhost:8787'});
await client.send({action:'SUBMIT_REPORT',data:{...report,channel_handle:'@queued'}});
assert.equal((await client.send({action:'GET_BLOCKED_CHANNELS'})).pendingCount, 1);
assert.ok((await client.send({action:'GET_BLOCKED_CHANNELS'})).syncError);
offline = false;
reportStatus = 401;
await client.send({action:'FORCE_SYNC'});
assert.equal((await client.send({action:'GET_BLOCKED_CHANNELS'})).pendingCount, 1, 'HTTP error retains queued report');
reportStatus = 201;
await client.send({action:'FORCE_SYNC'});
assert.equal((await client.send({action:'GET_BLOCKED_CHANNELS'})).pendingCount, 0);
community = [report];
await client.send({action:'FORCE_SYNC'});
const callsBefore = calls.length;
await client.send({action:'UNBLOCK_CHANNEL',handle:'@spam'});
assert.equal(calls.length, callsBefore, 'Personal exception never mutates server');
await client.send({action:'FORCE_SYNC'});
assert.equal((await client.send({action:'GET_BLOCKED_CHANNELS'})).channels['@spam'], undefined);
assert.ok((await client.send({action:'GET_BLOCKED_CHANNELS'})).allowed['@spam']);
await client.send({action:'REMOVE_EXCEPTION',handle:'@spam'});
assert.ok((await client.send({action:'GET_BLOCKED_CHANNELS'})).channels['@spam']);
community = [];
await client.send({action:'FORCE_SYNC'});
assert.equal((await client.send({action:'GET_BLOCKED_CHANNELS'})).channels['@spam'], undefined, 'Community revocation removes community-only block');
assert.equal((await client.send({action:'SET_SETTINGS',url:'https://evil.example',token:'x'})).success, false);
assert.equal((await client.send({action:'SET_SETTINGS',url:'http://localhost:8787',token:'x'}, 'https://www.youtube.com/watch')).success, false);
assert.equal((await client.send({action:'GET_SETTINGS'}, 'https://www.youtube.com/watch')).success, false);
await client.send({action:'SUBMIT_REPORT',data:{...report,channel_handle:'@local'}});
await client.send({action:'SET_SETTINGS',url:'https://another.workers.dev'});
assert.equal((await client.send({action:'GET_SETTINGS'})).reporterReady, true);
assert.equal(Object.keys((await client.send({action:'GET_BLOCKED_CHANNELS'})).channels).length, 0);
await client.send({action:'SUBMIT_REPORT',data:report});
assert.equal(calls.filter(c => c.url.startsWith('https://another.workers.dev/api/reports') && c.method === 'POST').length, 1, 'New API gets its own anonymous identity before reporting');
await client.send({action:'SET_SETTINGS',url:'http://localhost:8787'});
assert.equal((await client.send({action:'GET_SETTINGS'})).reporterReady, true);
assert.ok((await client.send({action:'GET_BLOCKED_CHANNELS'})).channels['@local']);
await Promise.all(Array.from({length:20}, () => client.send({action:'INCREMENT_HIDDEN_COUNT'})));
assert.equal((await client.send({action:'GET_BLOCKED_CHANNELS'})).hiddenCount, 20);
const restarted = backgroundHarness(async () => {throw new Error('Offline');}, client.storage);
assert.ok((await restarted.send({action:'GET_BLOCKED_CHANNELS'})).channels['@local'], 'Restart preserves local choices');
console.log('PASS background: queue/retry, local blocks, exceptions, revoked community blocks, scoped settings, restart, serialized updates');
